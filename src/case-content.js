export function chooseCaseVariant(seed, id) {
  if (seed === 314159) return "original";
  let n = seed >>> 0;
  for (const c of id) n = Math.imul(n ^ c.charCodeAt(0), 16777619) >>> 0;
  return CASE_VARIANTS[n % 3];
}
function get(base, variants, id, variant = "original") {
  const original = base.find((d) => d.id === id);
  if (!original) return null;
  if (variant === "original") return original;
  const index = CASE_VARIANTS.indexOf(variant) - 1;
  if (index < 0 || !variants[id]?.[index]) throw Error("案情版本无效。");
  const patch = variants[id][index];
  return {
    ...original,
    ...patch,
    clues: original.clues.map((c, i) => ({ ...c, ...patch.clues[i] })),
  };
}
export const countyCase = (s, id) =>
  get(CASES, countyVariants, id, s.cases[id]?.variant);
export const zhifuCase = (q, id) =>
  get(ZF_CASES, prefectVariants, id, q.cases[id]?.variant);
